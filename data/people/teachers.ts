export const activeTeachers = teachers.filter(
  (teacher) => teacher.status === "Active"
);


export const teachersOnLeave = teachers.filter(
  (teacher) => teacher.status === "On Leave"
);


export const teacherDepartments = [
  ...new Set(
    teachers.map((teacher) => teacher.department)
  ),
];


export const teacherSubjects = [
  ...new Set(
    teachers.flatMap((teacher) => teacher.subjects)
  ),
];


export const teacherCount = teachers.length;


export const totalTeachingExperience =
  teachers.reduce(
    (total, teacher) =>
      total + teacher.experience,
    0
  );


export const averageTeacherRating =
  Number(
    (
      teachers.reduce(
        (total, teacher) =>
          total + teacher.rating,
        0
      ) / teachers.length
    ).toFixed(2)
  );


// Find teacher by id
export const getTeacherById = (
  id: number
) =>
  teachers.find(
    (teacher) => teacher.id === id
  );


// Find teachers by department
export const getTeachersByDepartment = (
  department: string
) =>
  teachers.filter(
    (teacher) =>
      teacher.department === department
  );


// Find teachers by subject
export const getTeachersBySubject = (
  subject: string
) =>
  teachers.filter(
    (teacher) =>
      teacher.subjects.includes(subject)
  );